// Generates src/sim/sinLut.ts: the Q15 quarter-wave sine table of the deterministic maths (src/sim/detmath.ts).
// This tool is OUTSIDE the determinism lint, so it may use Math.sin; the result is rounded to integers and committed.
// tests/sim/lut.test.ts regenerates the text in memory and compares it with the committed file.
//
//   npm run gen:lut        writes src/sim/sinLut.ts
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

/** Steps per quarter turn: the full table has 4 * 1024 = 4096 steps per turn. */
export const QUARTER_STEPS = 1024;
/** 1.0 in Q15. */
export const Q15_ONE = 32768;

/** The quarter-wave table: entry i is round(sin(i / 4096 * 2 pi) * 32768) for i = 0..1024 (1025 entries, last = 32768). */
export function buildQuarterTable(): number[] {
  const out: number[] = [];
  for (let i = 0; i <= QUARTER_STEPS; i++) {
    out.push(Math.round(Math.sin((i / (QUARTER_STEPS * 4)) * 2 * Math.PI) * Q15_ONE));
  }
  return out;
}

/** The exact text of src/sim/sinLut.ts. */
export function buildLutSource(): string {
  const table = buildQuarterTable();
  const lines: string[] = [];
  for (let i = 0; i < table.length; i += 16) lines.push(`  ${table.slice(i, i + 16).join(', ')},`);
  return [
    '// GENERATED by tools/gen/lut.ts (npm run gen:lut). Do not edit by hand: tests/sim/lut.test.ts regenerates this',
    '// file in memory and fails when it differs.',
    '//',
    '// Quarter-wave sine in Q15: entry i is round(sin(i / 4096 turns) * 32768) for i = 0..1024. The top entry is 32768',
    '// (exactly 1.0), which does not fit a signed 16-bit integer, hence Uint16Array.',
    '',
    `export const SIN_QUARTER_STEPS = ${QUARTER_STEPS};`,
    '',
    'export const SIN_QUARTER_Q15: Uint16Array = new Uint16Array([',
    ...lines,
    ']);',
    '',
  ].join('\n');
}

export const LUT_PATH = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../../src/sim/sinLut.ts');

function main(): void {
  fs.writeFileSync(LUT_PATH, buildLutSource());
  console.log(`[gen:lut] wrote ${path.relative(process.cwd(), LUT_PATH)}`);
}

if (process.argv[1] !== undefined && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
